CREATE TABLE IF NOT EXISTS users(id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, role TEXT NOT NULL CHECK(role IN ('passenger','operator','admin')), salt TEXT NOT NULL, password TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1, flight_alerts INTEGER NOT NULL DEFAULT 1);

CREATE TABLE IF NOT EXISTS flights(id INTEGER PRIMARY KEY, number TEXT NOT NULL UNIQUE, city TEXT NOT NULL, gate TEXT NOT NULL, time INTEGER NOT NULL, direction INTEGER NOT NULL, status INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS tickets(id INTEGER PRIMARY KEY, owner INTEGER NOT NULL REFERENCES users(id), subject TEXT NOT NULL, state INTEGER NOT NULL DEFAULT 0, updated INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS messages(id INTEGER PRIMARY KEY, ticket INTEGER NOT NULL REFERENCES tickets(id), sender INTEGER NOT NULL REFERENCES users(id), body TEXT NOT NULL, sent INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS reads(user INTEGER NOT NULL REFERENCES users(id), ticket INTEGER NOT NULL REFERENCES tickets(id), last_message INTEGER NOT NULL, PRIMARY KEY(user,ticket));

CREATE TABLE IF NOT EXISTS bookings(id INTEGER PRIMARY KEY, user INTEGER NOT NULL REFERENCES users(id), flight INTEGER NOT NULL REFERENCES flights(id), code TEXT NOT NULL UNIQUE, checked INTEGER NOT NULL DEFAULT 0, seat TEXT, trip_tasks INTEGER NOT NULL DEFAULT 0, UNIQUE(user,flight));

CREATE INDEX IF NOT EXISTS message_ticket ON messages(ticket,id);

CREATE UNIQUE INDEX IF NOT EXISTS booking_seat ON bookings(flight,seat);

CREATE TABLE IF NOT EXISTS saved_flights(user INTEGER NOT NULL REFERENCES users(id), flight INTEGER NOT NULL REFERENCES flights(id), PRIMARY KEY(user,flight));

CREATE TABLE IF NOT EXISTS demo_days(day TEXT PRIMARY KEY NOT NULL);

CREATE TABLE IF NOT EXISTS notices(id INTEGER PRIMARY KEY, user INTEGER NOT NULL REFERENCES users(id), flight INTEGER NOT NULL REFERENCES flights(id), title TEXT NOT NULL, body TEXT NOT NULL, created INTEGER NOT NULL, seen INTEGER NOT NULL DEFAULT 0);

CREATE INDEX IF NOT EXISTS notices_user ON notices(user,id);

CREATE TABLE IF NOT EXISTS ops_log(id INTEGER PRIMARY KEY, actor INTEGER NOT NULL REFERENCES users(id), action TEXT NOT NULL, detail TEXT NOT NULL, created INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY, user INTEGER NOT NULL REFERENCES users(id), expires INTEGER NOT NULL);

CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user);

CREATE INDEX IF NOT EXISTS flights_time ON flights(direction,time);

CREATE TABLE IF NOT EXISTS reviews(id INTEGER PRIMARY KEY, user INTEGER NOT NULL REFERENCES users(id), rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5), body TEXT NOT NULL, created INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS travel_stamps(id INTEGER PRIMARY KEY, user INTEGER NOT NULL REFERENCES users(id), code TEXT NOT NULL UNIQUE, flight_number TEXT NOT NULL, city TEXT NOT NULL, departure INTEGER NOT NULL, seat TEXT, completed INTEGER NOT NULL);

CREATE INDEX IF NOT EXISTS travel_stamps_user ON travel_stamps(user,city,departure);
